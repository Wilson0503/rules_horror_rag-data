    for old in OUT_DIR.glob("*.txt"):
        old.unlink()
    rows = []
    for n, c in enumerate(CHUNKS, start=1):
        fname = f"{n:02d}_{c['fname']}.txt"
        (OUT_DIR / fname).write_text(render(c), encoding="utf-8")
        rows.append((fname, c))

    with open(OUT_DIR / "sources.csv", "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["檔案", "標題", "分類", "頁碼", "文件性質"])
        for fname, c in rows:
            w.writerow([fname, c["title"], c["category"], c["page"], c["nature"]])

